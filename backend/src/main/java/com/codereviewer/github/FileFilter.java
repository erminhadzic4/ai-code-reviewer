package com.codereviewer.github;

import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.Set;

/**
 * Decides which files of a repository are worth reviewing. Pure functions with no I/O.
 *
 * <p>A file is checked twice: by its path before its content is read, and by its content
 * afterwards. The lists below are rules of the product, not settings of an environment:
 * changing one changes the result for a commit that may already be cached, so a change
 * goes through a commit and a test.
 */
public final class FileFilter {

	/** Compared with a whole path segment, lower-case. Matches at any depth. */
	private static final Set<String> EXCLUDED_DIRECTORIES = Set.of(
			".git", "node_modules", "bower_components", "vendor", "third_party", "external", "deps",
			"target", "build", "dist", "out", "debug", "release", "x64", "coverage",
			".gradle", ".idea", ".vscode", ".vs", ".next", "__pycache__", ".venv", "venv");

	private static final String CMAKE_BUILD_PREFIX = "cmake-build-";

	private static final Set<String> LOCK_FILES = Set.of(
			"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "cargo.lock", "gemfile.lock",
			"poetry.lock", "uv.lock", "pipfile.lock", "composer.lock", "go.sum", "gradle.lockfile",
			"packages.lock.json");

	/** Licence, readme and project notice files, by the name before any suffix. */
	private static final Set<String> NOTICE_FILE_STEMS = Set.of(
			"README", "LICENSE", "LICENCE", "UNLICENSE", "COPYING", "NOTICE", "AUTHORS", "CONTRIBUTORS", "PATENTS",
			"CHANGELOG");

	private static final String NOTICE_SUFFIX_SEPARATORS = "-_.";

	private static final Set<String> NON_CODE_EXTENSIONS = Set.of("md", "txt", "rst", "csv", "svg");

	private static final Set<String> BINARY_EXTENSIONS = Set.of(
			// images
			"png", "jpg", "jpeg", "gif", "bmp", "ico", "webp", "tif", "tiff", "psd", "avif", "heic",
			// fonts
			"woff", "woff2", "ttf", "otf", "eot",
			// archives
			"zip", "tar", "gz", "tgz", "bz2", "xz", "7z", "rar", "zst",
			// audio and video
			"mp3", "wav", "ogg", "flac", "m4a", "mp4", "mov", "avi", "mkv", "webm",
			// documents
			"pdf", "doc", "docx", "xls", "xlsx", "ppt", "pptx", "odt", "ods",
			// compiled code
			"jar", "war", "ear", "class", "exe", "dll", "so", "dylib", "o", "obj", "a", "lib", "pdb",
			"pyc", "pyo", "wasm", "bin", "dat",
			// databases and key stores
			"db", "sqlite", "sqlite3", "jks", "keystore", "p12", "pfx");

	private static final List<String> GENERATED_NAME_SUFFIXES = List.of(
			".min.js", ".min.css", ".map", ".bundle.js", ".pb.go", "_pb2.py", ".g.dart", ".designer.cs");

	private static final String GENERATED_NAME_PART = ".generated.";

	/** Looked for in the first lines of a file, lower-case. */
	private static final List<String> GENERATED_MARKERS = List.of(
			"@generated", "code generated by", "do not edit", "auto-generated", "autogenerated",
			"automatically generated");

	static final int GENERATED_MARKER_LINES = 5;

	static final int MAX_LINE_LENGTH = 2000;

	static final int MAX_AVERAGE_LINE_LENGTH = 200;

	/** A short file with one long line is not minified code, so the average is ignored below this. */
	static final int MIN_LENGTH_FOR_AVERAGE = 2000;

	private FileFilter() {
	}

	/**
	 * Checks a path relative to the repository root, with {@code /} between segments.
	 *
	 * @return the reason to skip the file, or empty when its content should be read
	 */
	public static Optional<SkipReason> checkPath(String path) {
		String[] segments = path.split("/");
		for (int i = 0; i < segments.length - 1; i++) {
			String directory = segments[i].toLowerCase(Locale.ROOT);
			if (EXCLUDED_DIRECTORIES.contains(directory) || directory.startsWith(CMAKE_BUILD_PREFIX)) {
				return Optional.of(SkipReason.EXCLUDED_DIRECTORY);
			}
		}
		String name = segments[segments.length - 1];
		String lowerName = name.toLowerCase(Locale.ROOT);
		if (LOCK_FILES.contains(lowerName)) {
			return Optional.of(SkipReason.LOCK_FILE);
		}
		if (isNoticeFile(name)) {
			return Optional.of(SkipReason.NON_CODE);
		}
		if (hasGeneratedName(lowerName)) {
			return Optional.of(SkipReason.MINIFIED_OR_GENERATED);
		}
		String extension = extensionOf(lowerName);
		if (NON_CODE_EXTENSIONS.contains(extension) && !isBuildFileWithTextExtension(lowerName)) {
			return Optional.of(SkipReason.NON_CODE);
		}
		if (BINARY_EXTENSIONS.contains(extension)) {
			return Optional.of(SkipReason.BINARY);
		}
		return Optional.empty();
	}

	/**
	 * Checks the decoded text of a file that passed {@link #checkPath}.
	 *
	 * @return the reason to skip the file, or empty when it should be reviewed
	 */
	public static Optional<SkipReason> checkContent(String content) {
		if (content.isBlank()) {
			return Optional.of(SkipReason.EMPTY);
		}
		if (content.indexOf('\0') >= 0) {
			return Optional.of(SkipReason.BINARY);
		}
		if (hasGeneratedMarker(content) || looksMinified(content)) {
			return Optional.of(SkipReason.MINIFIED_OR_GENERATED);
		}
		return Optional.empty();
	}

	// The bare name in any case (LICENSE, License), or the upper-case name with a suffix
	// (LICENSE-MIT, COPYING.LESSER). Upper case is required for the second form so that
	// source files such as license.py stay in the review.
	private static boolean isNoticeFile(String name) {
		if (NOTICE_FILE_STEMS.contains(name.toUpperCase(Locale.ROOT))) {
			return true;
		}
		for (String stem : NOTICE_FILE_STEMS) {
			if (name.length() > stem.length() && name.startsWith(stem)
					&& NOTICE_SUFFIX_SEPARATORS.indexOf(name.charAt(stem.length())) >= 0) {
				return true;
			}
		}
		return false;
	}

	// CMakeLists.txt, requirements.txt and variants such as requirements-dev.txt are build
	// files, not prose. Checked by file name only, after the directory rules.
	private static boolean isBuildFileWithTextExtension(String lowerName) {
		return lowerName.equals("cmakelists.txt")
				|| (lowerName.startsWith("requirements") && lowerName.endsWith(".txt"));
	}

	private static boolean hasGeneratedName(String lowerName) {
		if (lowerName.contains(GENERATED_NAME_PART)) {
			return true;
		}
		return GENERATED_NAME_SUFFIXES.stream().anyMatch(lowerName::endsWith);
	}

	// A leading dot marks a hidden file, not an extension: ".gitignore" has none.
	private static String extensionOf(String lowerName) {
		int dot = lowerName.lastIndexOf('.');
		return dot > 0 ? lowerName.substring(dot + 1) : "";
	}

	private static boolean hasGeneratedMarker(String content) {
		int end = 0;
		for (int line = 0; line < GENERATED_MARKER_LINES && end < content.length(); line++) {
			int newline = content.indexOf('\n', end);
			end = newline < 0 ? content.length() : newline + 1;
		}
		String head = content.substring(0, end).toLowerCase(Locale.ROOT);
		return GENERATED_MARKERS.stream().anyMatch(head::contains);
	}

	private static boolean looksMinified(String content) {
		int lines = 0;
		int characters = 0;
		int start = 0;
		while (start < content.length()) {
			int newline = content.indexOf('\n', start);
			int end = newline < 0 ? content.length() : newline;
			int length = end - start;
			if (length > MAX_LINE_LENGTH) {
				return true;
			}
			lines++;
			characters += length;
			start = end + 1;
		}
		return content.length() >= MIN_LENGTH_FOR_AVERAGE && characters / lines > MAX_AVERAGE_LINE_LENGTH;
	}

}
